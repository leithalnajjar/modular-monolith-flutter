// tools/boundary_check/lib/src/module_map.dart
import 'owners.dart';
import 'workspace.dart';

/// A Markdown table of every package: its layer, its owners, what it
/// depends on and what depends on it. Generated from the pubspecs and
/// CODEOWNERS, so it is never out of date when the check runs.
String moduleMap(List<WorkspacePackage> packages, CodeOwners? owners) {
  final names = {for (final pkg in packages) pkg.name};
  final usedBy = <String, List<String>>{};
  for (final pkg in packages) {
    for (final dep in pkg.dependencies.where(names.contains)) {
      (usedBy[dep] ??= []).add(pkg.name);
    }
  }
  String list(Iterable<String> items) =>
      items.isEmpty ? '' : (items.toList()..sort()).join(', ');

  return [
    '# Bazaar packages',
    '',
    'Generated by `dart run boundary_check:modules --write docs/modules.md`.',
    'Do not edit by hand: `tool/check.dart` fails when this file is stale.',
    '',
    '| Package | Layer | Owners | Depends on | Used by |',
    '|---|---|---|---|---|',
    for (final pkg in packages)
      '| `${pkg.dir}` | ${pkg.layer.name} '
          '| ${owners?.ruleFor(pkg.dir)?.owners.join(' ') ?? ''} '
          '| ${list(pkg.dependencies.where(names.contains))} '
          '| ${list(usedBy[pkg.name] ?? const [])} |',
    '',
  ].join('\n');
}
